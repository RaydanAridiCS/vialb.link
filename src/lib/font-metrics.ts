/** Width, in ems, of a glyph outside the table: CJK and emoji are about a full em, other scripts a bit under. */
const WIDE =
  /[\u1100-\u11ff\u2e80-\ua4cf\uac00-\ud7a3\uf900-\ufaff\ufe30-\ufe6f\uff00-\uffef\u{1f000}-\u{1faff}]/u;

/** Advance width of one character in ems. Combining marks take no room. */
export function glyphWidth(char: string, bold: boolean): number {
  const cp = char.codePointAt(0) ?? 0;
  if (cp >= 0x300 && cp <= 0x36f) return 0;
  if (cp >= 32 && cp <= 255) {
    const w = (bold ? BOLD : REGULAR)[cp - 32] ?? 0;
    if (w > 0) return w / 1000;
  }
  if (WIDE.test(char)) return 1;
  return bold ? 0.78 : 0.7;
}

/** Width in pixels of `text` at `size` px. */
export function textWidth(text: string, size: number, bold = false): number {
  let em = 0;
  for (const char of text) em += glyphWidth(char, bold);
  return em * size;
}
